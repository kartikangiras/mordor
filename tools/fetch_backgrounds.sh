#!/usr/bin/env bash
# Fetch the page backdrops from NASA Worldview (GIBS snapshots) into web/public/bg/ and write the
# tiny inline placeholders to web/src/config/backdrops.ts. NASA imagery is in the public domain;
# the pages credit "NASA Worldview". Re-run to refresh; the images are committed with the web.
#   tools/fetch_backgrounds.sh            # all four
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=web/public/bg
mkdir -p "$OUT"
W=1920; H=1200
API="https://wvs.earthdata.nasa.gov/api/v1/snapshot?REQUEST=GetSnapshot&CRS=EPSG:4326&FORMAT=image/jpeg&WIDTH=$W&HEIGHT=$H"

# name|date|bbox (S,W,N,E)|layers
SET=(
  "fires|2024-11-10|27.5,73.5,32.5,80|VIIRS_SNPP_CorrectedReflectance_TrueColor,VIIRS_SNPP_Thermal_Anomalies_375m_Day"
  "haze|2024-11-14|26.5,74,31.5,80.5|VIIRS_SNPP_CorrectedReflectance_TrueColor"
  "night|2016-01-01|25.5,71.5,33,83.5|VIIRS_Black_Marble"
  "clear|2024-10-24|26.5,74,31.5,80.5|VIIRS_SNPP_CorrectedReflectance_TrueColor"
)
for row in "${SET[@]}"; do
  IFS='|' read -r name date bbox layers <<<"$row"
  raw="$OUT/$name.raw.jpg"
  wrap=$(echo "$layers" | awk -F, '{ for (i = 1; i <= NF; i++) printf "%sx", (i > 1 ? "," : "") }')   # one WRAP value per layer
  code=$(curl -sS -o "$raw" -w '%{http_code}' "$API&TIME=${date}T00:00:00Z&BBOX=$bbox&LAYERS=$layers&WRAP=$wrap")
  if [ "$code" != "200" ] || ! file "$raw" | grep -q JPEG; then echo "$name: HTTP $code, not a JPEG" >&2; rm -f "$raw"; exit 1; fi
  python3 - "$raw" "$OUT/$name.jpg" <<'PY'
import pathlib, sys
from PIL import Image
src, dst = sys.argv[1], sys.argv[2]
im = Image.open(src).convert("RGB")
for q in (78, 72, 66, 60, 54):   # the first quality that lands under 350 KB
    im.save(dst, "JPEG", quality=q, optimize=True, progressive=True)
    if pathlib.Path(dst).stat().st_size <= 350_000:
        break
PY
  rm -f "$raw"
  echo "$name.jpg $(du -k "$OUT/$name.jpg" | cut -f1) KB"
done

python3 - "$OUT" <<'PY'
import base64, io, sys, pathlib
from PIL import Image, ImageFilter
out = pathlib.Path(sys.argv[1])
lines = ["// Generated by tools/fetch_backgrounds.sh: the page backdrops and their inline placeholders.",
         "// NASA Worldview (GIBS) snapshots; NASA imagery is in the public domain.",
         "export type BackdropId = 'fires' | 'haze' | 'night' | 'clear'",
         "export const BACKDROPS: Record<BackdropId, { src: string; lqip: string; credit: string }> = {"]
credits = {"fires": "NASA Worldview · VIIRS true colour and fire detections, 10 Nov 2024",
           "haze": "NASA Worldview · VIIRS true colour, 14 Nov 2024",
           "night": "NASA Worldview · Black Marble night lights",
           "clear": "NASA Worldview · VIIRS true colour, 24 Oct 2024"}
for name in ("fires", "haze", "night", "clear"):
    im = Image.open(out / f"{name}.jpg").convert("RGB")
    small = im.resize((32, 20), Image.LANCZOS).filter(ImageFilter.GaussianBlur(1))
    buf = io.BytesIO(); small.save(buf, "JPEG", quality=50)
    b64 = base64.b64encode(buf.getvalue()).decode()
    lines.append(f"  {name}: {{ src: '/bg/{name}.jpg', lqip: 'data:image/jpeg;base64,{b64}', credit: '{credits[name]}' }},")
lines.append("}")
pathlib.Path("web/src/config/backdrops.ts").write_text("\n".join(lines) + "\n")
print("web/src/config/backdrops.ts written")
PY
